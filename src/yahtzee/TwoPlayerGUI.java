            PlayerBNameField.setText(tempNameB);
            playerB.setPlayerName(tempNameB);
            playerB.scoreBoard.setOnesValue(Integer.parseInt(br.readLine()));
            playerB.scoreBoard.setTwosValue(Integer.parseInt(br.readLine()));
            playerB.scoreBoard.setThreesValue(Integer.parseInt(br.readLine()));
            playerB.scoreBoard.setFoursValue(Integer.parseInt(br.readLine()));
            playerB.scoreBoard.setFivesValue(Integer.parseInt(br.readLine()));
            playerB.scoreBoard.setSixsValue(Integer.parseInt(br.readLine()));
            playerB.scoreBoard.setTotalUpperSection(Integer.parseInt(br.readLine()));
            playerB.scoreBoard.setThreeOfAKindValue(Integer.parseInt(br.readLine()));
            playerB.scoreBoard.setFourOfAKindValue(Integer.parseInt(br.readLine()));
