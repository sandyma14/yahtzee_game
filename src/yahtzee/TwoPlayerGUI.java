    private void rollButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_rollButtonActionPerformed
        // TODO add your handling code here:
        if (evt.getSource() == rollButton) {
            //-----------Handle the number of roll left------
            int rollLeft = currentPlayer.getNumRollLeft();
            if (rollLeft == 3) {
                // First roll of the turn: roll all 5 dice fresh
                diceRoll = rollDice(5);
                rollLeft--;
                currentPlayer.setNumRollLeft(rollLeft);
                RollLeftDisplay.setText("Roll Left: " + rollLeft);

                //Clear any locks players made before their first roll
                for (int i = 0; i < lockIndexes.length; i++) {
                    lockIndexes[i] = -1;
                }
                dice1.setBorder(BorderFactory.createLineBorder(Color.white, 4, true));
                dice2.setBorder(BorderFactory.createLineBorder(Color.white, 4, true));
                dice3.setBorder(BorderFactory.createLineBorder(Color.white, 4, true));
                dice4.setBorder(BorderFactory.createLineBorder(Color.white, 4, true));
                dice5.setBorder(BorderFactory.createLineBorder(Color.white, 4, true));

            } else if (rollLeft > 0) {
                // Subsequent rerolls: respect the locked indexes
                diceRoll = rerollDice(diceRoll, lockIndexes);
                rollLeft--;
                currentPlayer.setNumRollLeft(rollLeft);
                RollLeftDisplay.setText("Roll Left: " + rollLeft);
            } else {
                return; //Once a return statement is executed, the method exits, and no further conditions are evaluated.
            }

            //Display all results and reset all scoreboard borders for new rolls
            displayAllDice();
            displayAllScores();
            resetAllPlayerABorders();
            resetAllPlayerBBorders();
        }
    }//GEN-LAST:event_rollButtonActionPerformed

