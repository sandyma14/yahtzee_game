    private void endTurn() {
        // Reset the current player's roll count for their next turn
        currentPlayer.setNumRollLeft(3);
        RollLeftDisplay.setText("Roll Left: " + 3);

        //Reset temp score 
        playerA.setTempScore(-1);
        playerA.setScoreType(null);
        playerB.setTempScore(-1);
        playerB.setScoreType(null);

        // Clear all locked indexes back to -1
        for (int i = 0; i < lockIndexes.length; i++) {
            lockIndexes[i] = -1;
        }
        
        //Reset all current displayed score, border but keep the logged score
        resetAllDiceDisplay();
        resetAllPlayerAText();
        resetAllPlayerBText();
        resetAllPlayerABorders();
        resetAllPlayerBBorders();
        // To not reset score already logged 
        finalizeScore();

        // Swap to the other player 
        if (currentPlayer == playerA) {
            //From A to B
            currentPlayer = playerB;
            rollButton.setBackground(LightBlue);
            playButton.setBackground(LightBlue);
            currentColor = Blue;
        } else {
            //From B to A
            currentPlayer = playerA;
            rollButton.setBackground(LightRed);
            playButton.setBackground(LightRed);
            currentColor = Red;
        }
        //Set the scoreBoard variable to current player's 
        scoreBoard = currentPlayer.getScoreBoard();

        // Set round left
        numRound += 0.5; //If we plus 0.5 each player it will be plus one for one full round
        //Display round to the green tracker on the top
        roundTracker.setText("Round " + (int) numRound);
        
        //The moment playerB entered their last score endGame
        if (numRound == 14.0) {
            endGame();
        }
    }

    private void endGame() {
        //Get the Variables to pass to the EndGamesScreen 
        String playerAName = playerA.getPlayerName();
        //Handle when player don't input their name
        if (playerAName.equals("Enter Player A's Name")) {
            playerA.setPlayerName("Player A");
        }
        String playerBName = playerB.getPlayerName();
        //Handle when player don't input their name
        if (playerBName.equals("Enter Player B's Name")) {
            playerB.setPlayerName("Player B");
        }
        int scoreA = playerA.getScoreBoard().getGrandTotal();
        int scoreB = playerB.getScoreBoard().getGrandTotal();

        //Determine who is the winner
        String winnerName = null;
        if (scoreA == scoreB) {
            winnerName = playerAName + " and " + playerBName;
        } else if (scoreA > scoreB) {
            winnerName = playerAName;
        } else if (scoreB > scoreA) {
            winnerName = playerBName;
        }

        // Call the end game screen
        new EndGameScreen(winnerName, playerAName, playerBName, scoreA, scoreB).setVisible(true);

        //Close this TwoPlayerGUI
        this.dispose();

    }

