    private void lockDice(javax.swing.JButton dice, int indexDice) {
        //This is for the main program
        if (lockIndexes[indexDice] == -1) { //If the dice was unlocked
            lockIndexes[indexDice] = indexDice; // Lock it
            dice.setBorder(BorderFactory.createLineBorder(currentColor, 4, true)); //Give it a border
        } else {
            lockIndexes[indexDice] = -1; //Else if it was locked, unclock it
            dice.setBorder(BorderFactory.createLineBorder(Color.white, 4, true)); //clean boarder
        }
    }

    private void displayDiceBorder(javax.swing.JButton dice, int indexDice) {
        //This is for displaying the dice boarder after loading the game
        if (lockIndexes[indexDice] == -1) { //If the dice was locked give it a bprder
            dice.setBorder(BorderFactory.createLineBorder(Color.white, 4, true));
        } else { //Else no boarder
            dice.setBorder(BorderFactory.createLineBorder(currentColor, 4, true));
        }
    }

